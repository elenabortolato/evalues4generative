"""Minimal example: auditing a language-model API with the Monte Carlo e-process.

The setting of Section 5.6 of the paper, stripped to one run. An API claims to
serve a language model P (Qwen2.5-1.5B-Instruct at 8 bits) but may answer some
queries with a cheaper substitute. The auditor can send prompts to the API and
can run P on their own computer, but sees no probabilities, only replies.

At each step the auditor
  1. chooses one of four prompts, using the past only;
  2. sends it to the API and receives the real reply X_t;
  3. generates M replies of P to the same prompt (the simulations);
  4. bets with the Monte Carlo factor
         E_t = (M+1) T(X_t) / {T(X_t) + sum_j T(Y_tj)},
     where T is the learned score, fixed before X_t is seen;
  5. updates the score with the new reply and its simulations.
The auditor raises an alarm when the wealth (the running product of the bets,
hedged over the betting fraction) reaches 1/alpha.

No language model is needed: the replies are drawn from the real outputs
stored in data/llm_audit/replies.json (generated by
experiments/exp16_llm_generate.py). Only the routing is simulated. The full
experiment, with the baselines and many replications, is
experiments/exp16_llm_audit.py.

Usage (a few seconds each):
    python examples/llm_audit_minimal.py                    # the API cheats
    python examples/llm_audit_minimal.py --honest           # the API is honest
    python examples/llm_audit_minimal.py --substitute 05b   # a smaller model
    python examples/llm_audit_minimal.py --honest --ignore-action
        # the twin answers a random prompt instead of the one sent to the API:
        # false alarm although the API is honest (Proposition 2)
"""

from __future__ import annotations

import argparse
import json
import sys
import zlib
from collections import Counter
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from e4g.evalues import LambdaMixture, mc_factor  # noqa: E402
from e4g.learners import BLRRatio  # noqa: E402

# The four prompts, as sent to the models (experiments/exp16_llm_generate.py).
PROMPTS = {
    "digits": "Generate exactly 8 independent uniformly random digits from 0 to 9. "
              "Output only the compact digit string, no separators.",
    "number": "Choose one uniformly random integer between 1 and 100 inclusive. "
              "Output only the integer.",
    "color": "Name one random color. Output only the color name.",
    "coin": "Flip a fair coin 6 times. Output only the results as a string of H and T, "
            "no separators.",
}
NAMES = list(PROMPTS)
K, D = len(NAMES), 32
MODELS = {"q8_0": "Qwen2.5-1.5B, 8 bits (advertised)", "q4_k_m": "Qwen2.5-1.5B, 4 bits",
          "q3_k_m": "Qwen2.5-1.5B, 3 bits", "05b": "Qwen2.5-0.5B, 4 bits"}


def text_features(s: str) -> np.ndarray:
    """Character unigrams and bigrams hashed into 30 bins, length, whitespace
    (the features of experiments/exp16_llm_audit.py)."""
    f = np.zeros(D)
    grams = list(s) + [s[i:i + 2] for i in range(len(s) - 1)]
    for g in grams:
        f[zlib.crc32(g.encode()) % (D - 2)] += 1.0
    if grams:
        f[: D - 2] /= np.sqrt(len(grams))
    f[D - 2], f[D - 1] = len(s) / 10.0, float(any(c.isspace() for c in s))
    return f


def features(k: int, s: str) -> np.ndarray:
    """One block of features per prompt, so that the score can differ by prompt."""
    z = np.zeros(K * D)
    z[k * D:(k + 1) * D] = text_features(s)
    return z


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--honest", action="store_true", help="the API always serves P")
    ap.add_argument("--substitute", default="q4_k_m", choices=["q4_k_m", "q3_k_m", "05b"])
    ap.add_argument("--fraction", type=float, default=0.3,
                    help="fraction of queries sent to the substitute")
    ap.add_argument("--ignore-action", action="store_true",
                    help="the twin answers a random prompt (invalid on purpose)")
    ap.add_argument("--M", type=int, default=8, help="simulations per step")
    ap.add_argument("--alpha", type=float, default=0.05)
    ap.add_argument("--horizon", type=int, default=400)
    ap.add_argument("--seed", type=int, default=1)
    args = ap.parse_args()
    rng = np.random.default_rng(args.seed)

    raw = json.loads((ROOT / "data/llm_audit/replies.json").read_text())
    pool = {tuple(key.split("|")): replies for key, replies in raw.items()}

    # What the data look like: the five most frequent replies to each prompt.
    print("Most frequent replies of the advertised model P and of the substitute")
    for p in NAMES:
        print(f'\n  prompt "{p}": {PROMPTS[p]}')
        for q in ["q8_0", args.substitute]:
            top = Counter(pool[(q, p)]).most_common(5)
            n = len(pool[(q, p)])
            shown = ", ".join(f"{r!r} {c / n:.0%}" for r, c in top)
            print(f"    {MODELS[q]:<35} {shown}")

    cheat = 0.0 if args.honest else args.fraction
    print(f"\nThe API sends {cheat:.0%} of the queries to {MODELS[args.substitute]}."
          f"\nThe twin answers {'a RANDOM prompt' if args.ignore_action else 'the same prompt'}."
          f" Alarm when the wealth reaches 1/alpha = {1 / args.alpha:.0f}.\n")

    # The score: a Bayesian logistic regression of real against simulated
    # replies; features standardised with 200 replies of P per prompt, drawn
    # before the audit (no reply of the substitute is ever used).
    twin = np.array([features(k, s) for k, p in enumerate(NAMES)
                     for s in rng.choice(pool[("q8_0", p)], 200)])
    learner = BLRRatio(prior_var=1.0, mode="predictive", feature_map=lambda z: z)
    learner.fit_scaler(twin)
    wealth = LambdaMixture()
    n_asked, gain = np.zeros(K), np.zeros(K)

    print(f"{'step':>4}  {'prompt':<7} {'real reply':<14} {'served by':<10} {'bet':>6} {'wealth':>8}")
    for t in range(1, args.horizon + 1):
        # 1. choose the prompt from the past only: an upper confidence bound on
        #    the log growth of each prompt, each prompt kept above a tenth
        if t <= 2 * K:
            a = (t - 1) % K
        elif n_asked.min() < 0.1 * t:
            a = int(np.argmin(n_asked))
        else:
            a = int(np.argmax(gain / n_asked + np.sqrt(np.log(t) / n_asked)))
        p = NAMES[a]

        # 2. the API's reply (who answered is hidden from the auditor)
        served = args.substitute if rng.random() < cheat else "q8_0"
        x = rng.choice(pool[(served, p)])

        # 3. M replies of P, run locally on the same prompt
        p_twin = NAMES[rng.integers(K)] if args.ignore_action else p
        ys = rng.choice(pool[("q8_0", p_twin)], args.M)

        # 4. the bet: the score is fixed before x is seen
        z = np.array([features(a, s) for s in [x, *ys]])
        s = learner.score(z)
        e = mc_factor(s[0], s[1:])
        w = wealth.update(e)
        if t <= 12 or t % 25 == 0 or w >= 1 / args.alpha:
            shown = " ".join(x.split())[:14]
            print(f"{t:>4}  {p:<7} {shown:<14} {served:<10} {e:6.2f} {w:8.2f}")
        if w >= 1 / args.alpha:
            print(f"\nALARM after {t} queries "
                  f"(prompts asked: {dict(zip(NAMES, n_asked.astype(int).tolist()))}).")
            if args.honest:
                print("This is a FALSE alarm: the API is honest"
                      + (", but the twin ignored the prompt." if args.ignore_action else "."))
            return

        # 5. learn after the bet
        learner.update(z[:1], z[1:])
        n_asked[a] += 1
        gain[a] += np.log(0.5 + 0.5 * e)

    print(f"\nNo alarm in {args.horizon} queries (final wealth {w:.2f}).")


if __name__ == "__main__":
    main()
