REF = re.compile(r"\\(ref|eqref)\{([^}]*)\}")


def run_latex(name: str, bibtex: bool = True, passes: int = 3) -> str:
    def run(*cmd):
        subprocess.run(cmd, cwd=HERE, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
    run("pdflatex", "-interaction=nonstopmode", name + ".tex")
    if bibtex:
        run("bibtex", name)
    for _ in range(passes - 1):
        run("pdflatex", "-interaction=nonstopmode", name + ".tex")
    return (HERE / (name + ".log")).read_text(errors="replace")


def check(log: str, name: str) -> None:
    lines = log.splitlines()
    errors = [l for l in lines if l.startswith("!")]
    undefined = [l for l in lines if "undefined" in l]
    overfull = [l for l in lines if l.startswith("Overfull")]
    if errors or undefined:
        raise SystemExit(f"{name}: {errors[:3]} {undefined[:3]}")
    print(f"{name}: compiled, {len(overfull)} overfull boxes")


def labels(aux: Path) -> dict[str, str]:
    return dict(re.findall(r"\\newlabel\{([^}]*)\}\{\{([^}]*)\}", aux.read_text()))


def resolve(text: str, numbers: dict[str, str], local: set[str]) -> str:
    """Write references to labels of the other document as plain numbers."""
    def rep(m):
        cmd, lab = m.groups()
        if lab in local:
            return m.group(0)
        return f"({numbers[lab]})" if cmd == "eqref" else numbers[lab]
    return REF.sub(rep, text)


def manuscript(src: str, blind: int, sup: dict[str, str]) -> str:
    body = src[src.index(r"\section{Introduction}"):src.index(r"\section*{Data availability}")]
    body = body.replace("Code, results and figures are in the repository \\texttt{evalues4generative};\nall runs are seeded.\n", "")
    old = "Table~\\ref{tab:notation} in the\nAppendix."
    assert old in body, "notation sentence"
    body = body.replace(old, f"Table~{sup['tab:notation']} of the\nSupplement.")
    body = re.sub(r"Appendix~\\ref\{(app:[a-z]+)\}",
                  lambda m: f"Section~{sup[m.group(1)]} of the Supplement", body)
    assert "Appendix~\\ref" not in body and "\\ref{app:" not in body
    # floats single-spaced, as the ASA template allows, and free to form a page of
    # their own: at 12pt with spacing 1.45 the large tables of Section 5.6 do not
    # fit at the top of a page and would otherwise all move after the references
    body = re.sub(r"\\begin\{(table|figure)\}\[t\]\n",
                  lambda m: f"\\begin{{{m.group(1)}}}[tp]\n\\spacingset{{1}}\n", body)
    repo = (r"\if0\blind, at " + REPO + r"\fi\if1\blind{} (link removed for blind review)\fi")
    back = (BACKMATTER.replace("%REPO%", repo)
            .replace("%S_FIRST%", sup["app:notation"]).replace("%S_LAST%", sup["app:timeline"]))
    return (PREAMBLE.replace("%BLIND%", str(blind)).replace("%ABSTRACT%", ABSTRACT)
            + body.rstrip() + "\n" + back)


def supplement(sup_src: str, appendix: str, blind: int, main: dict[str, str] | None) -> str:
    pre, rest = sup_src.split("\\begin{document}", 1)
    pre = "\n".join(l for l in pre.splitlines() if not l.startswith("% ")) + "\n"
    pre = "%% JASA supplementary material, generated by make_jasa.py.\n" + pre.lstrip("\n")
    if "\\usepackage{adjustbox}" not in pre:
        pre = pre.replace("\\usepackage{booktabs}\n", "\\usepackage{booktabs}\n\\usepackage{adjustbox}\n", 1)
    pre = pre.replace("\\usepackage{booktabs}\n", "\\usepackage{booktabs}\n\\usepackage{float}\n", 1)
    pre = pre.replace("\\graphicspath{{../figures/}}", "\\graphicspath{{./}}\n"
                      "\\setlength{\\emergencystretch}{3em}")
    i, j = pre.index("\\title{"), pre.index("\\date{\\today}") + len("\\date{\\today}")
    pre = pre[:i] + SUP_TITLE.replace("%BLIND%", str(blind)) + pre[j:]
    assert SUP_INTRO_OLD in rest, "supplement introduction"
    rest = rest.replace(SUP_INTRO_OLD, SUP_INTRO_NEW)
    body = rest[:rest.index("\\bibliographystyle{plainnat}")]
    app = appendix.replace("Appendix~\\ref{", "Section~\\ref{")
    old = "the variants in the Supplement\nuse the original seeds"
    assert old in app, "seeds sentence"
    app = app.replace(old, "the variants in Section~\\ref{sec:more}\nuse the original seeds")
    # the notation table opens a new page, right under its heading; as a float
    # it is too tall for the top of a page and would move to the end
    head = "\\section{Notation}\\label{app:notation}"
    assert head in app, "notation heading"
    app = app.replace(head, "\\clearpage\n" + head, 1)
    k = app.index("\\begin{table}[h]", app.index(head))
    app = app[:k] + "\\begin{table}[H]" + app[k + len("\\begin{table}[h]"):]
    if main is not None:
        local = set(re.findall(r"\\label\{([^}]*)\}", body + app))
        app = resolve(app, main, local)
    return (pre + "\\begin{document}" + body.rstrip() + "\n\n" + app.strip() + "\n\n"
            "\\bibliographystyle{chicago}\n\\bibliography{references}\n\n\\end{document}\n")


def acc_form() -> None:
    """The ACC form, a PDF that JASA asks for with the initial submission."""
    if shutil.which("pandoc") is None:
        print("ACC_form: pandoc not found, PDF not built")
        return
    body = subprocess.run(["pandoc", "ACC_form.md", "-t", "latex"], cwd=HERE,
                          capture_output=True, text=True, check=True).stdout
    (HERE / "ACC_form.tex").write_text(ACC_PREAMBLE + body + "\n\\end{document}\n")
    check(run_latex("ACC_form", bibtex=False, passes=2), "ACC_form")


def main() -> None:
    src = (PAPER / "main.tex").read_text()
    sup_src = (PAPER / "supplement.tex").read_text()
    appendix = src[src.index("\\appendix") + len("\\appendix"):src.index("\\end{document}")]

    shutil.copy(PAPER / "references.bib", HERE / "references.bib")
    for f in sorted(set(re.findall(r"\\includegraphics(?:\[[^]]*\])?\{([^}]*)\}", src + sup_src))):
        shutil.copy(FIGS / f, HERE / f)

    # 1. the supplement's own numbers (sections S6-S9, the notation table)
    (HERE / "supplement.tex").write_text(supplement(sup_src, appendix, 0, None))
    run_latex("supplement", bibtex=False, passes=2)
    sup = labels(HERE / "supplement.aux")
    # 2. the article, pointing to them
    for name, blind in (("manuscript", 0), ("manuscript_blinded", 1)):
        (HERE / f"{name}.tex").write_text(manuscript(src, blind, sup))
        check(run_latex(name), name)
    main_numbers = labels(HERE / "manuscript.aux")
    # 3. the supplement, with the article's numbers
    for name, blind in (("supplement", 0), ("supplement_blinded", 1)):
        (HERE / f"{name}.tex").write_text(supplement(sup_src, appendix, blind, main_numbers))
        check(run_latex(name), name)
    assert labels(HERE / "supplement.aux")["tab:notation"] == sup["tab:notation"]
    acc_form()
    for name in ("manuscript", "manuscript_blinded", "supplement", "supplement_blinded",
                 "ACC_form"):
        pages = subprocess.run(["pdfinfo", name + ".pdf"], cwd=HERE, capture_output=True,
                               text=True).stdout
        print(name, [l.split()[-1] for l in pages.splitlines() if l.startswith("Pages")])


if __name__ == "__main__":
    main()
