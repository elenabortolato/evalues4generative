# The abstract of ../main.tex shortened to 200 words, as JASA requires.
ABSTRACT = r"""Multi-arm multi-stage trials, bandits and digital twins collect data
adaptively. We test whether a simulator reproduces such a system with
e-processes, which allow optional stopping. A score learned by classifying real
against simulated outcomes becomes an exact bet when normalised over $M$ fresh
simulations. Under adaptive allocation, validity follows from exchangeability
if the simulator is run under the action taken and from the current state.
This conditioning is necessary: a simulator that ignores the action makes the
expected bet tend to $1+\chi^2$, and the wealth grows exponentially under the
null. The actions also add power: in an audit of a language-model API,
choosing the prompts adaptively saves every score up to 61\% of the queries.
The growth rate of any score splits into a simulation cost, $M/(M+1)$ for local
alternatives, and a learning cost, $\KL(Q\|\tilde T)$, with $\tilde T$ the
score's forecast. The bet is a likelihood in the score's parameter, so Bayesian
updating is exact: posterior-predictive bets stay pathwise within $d\log t$ of
the best score in hindsight. In a multi-arm multi-stage trial of insulin
dosing, the monitor controls false alarms and identifies the failing arms;
monitors that ignore the allocation or the participants' history do not."""

