"""Build the JASA (Theory and Methods) submission from ../main.tex and ../supplement.tex.

JASA uses the ASA template, as JCGS does, and reviews Theory and Methods papers
double-blind; abstracts have at most 200 words, and long appendices go in the
supplementary material. The script writes, in this folder:

- manuscript.tex, manuscript_blinded.tex: the article, with and without the
  author; the appendices of ../main.tex are moved to the supplement;
- supplement.tex, supplement_blinded.tex: Sections S1-S5 of ../supplement.tex,
  followed by the appendices of ../main.tex as Sections S6-S9 (notation,
  proofs, experimental details, timing relative to concurrent work);
- the PDFs of all four, references.bib and the figures.

The body of the article is the body of ../main.tex, unchanged except for the
references to the appendices, so the versions cannot drift apart. The abstract
is the 200-word version below. References between the article and the
supplement are written as plain numbers, read from the .aux file of the other
document, so that each file compiles on its own (also on Overleaf).

Run from this folder (needs pdflatex and bibtex):

    python make_jasa.py
"""

