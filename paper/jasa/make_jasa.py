REF = re.compile(r"\\(ref|eqref)\{([^}]*)\}")


def run_latex(name: str, bibtex: bool = True, passes: int = 3) -> str:
    def run(*cmd):
        subprocess.run(cmd, cwd=HERE, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
    run("pdflatex", "-interaction=nonstopmode", name + ".tex")
    if bibtex:
        run("bibtex", name)
    for _ in range(passes - 1):
        run("pdflatex", "-interaction=nonstopmode", name + ".tex")
    return (HERE / (name + ".log")).read_text(errors="replace")


def check(log: str, name: str) -> None:
    lines = log.splitlines()
    errors = [l for l in lines if l.startswith("!")]
    undefined = [l for l in lines if "undefined" in l]
    overfull = [l for l in lines if l.startswith("Overfull")]
    if errors or undefined:
        raise SystemExit(f"{name}: {errors[:3]} {undefined[:3]}")
    print(f"{name}: compiled, {len(overfull)} overfull boxes")


def labels(aux: Path) -> dict[str, str]:
    return dict(re.findall(r"\\newlabel\{([^}]*)\}\{\{([^}]*)\}", aux.read_text()))


def resolve(text: str, numbers: dict[str, str], local: set[str]) -> str:
    """Write references to labels of the other document as plain numbers."""
    def rep(m):
        cmd, lab = m.groups()
        if lab in local:
            return m.group(0)
        return f"({numbers[lab]})" if cmd == "eqref" else numbers[lab]
    return REF.sub(rep, text)



