WIDE = ["tab:objects", "tab:concurrent", "tab:llm", "tab:trial", "tab:notation"]


def shrink_wide_tables(tex: str) -> str:
    """Scale each listed table to the text width.

    sn-jnl.cls redefines tabular inside table floats, so the tabular is
    typeset into a box just before the float, where tabular is the standard
    one, and the float scales the box inside a one-cell tabular, which the
    class needs to place the caption and label.
    """
    for lab in WIDE:
        k = tex.find("\\label{" + lab + "}")
        if k < 0:
            continue
        start = tex.rindex("\\begin{table}", 0, k)
        i = tex.index("\\begin{tabular}", k)
        j = tex.index("\\end{tabular}", i) + len("\\end{tabular}")
        tab = tex[i:j]
        tex = (tex[:i] + "\\begin{tabular}{@{}c@{}}\\resizebox{\\textwidth}{!}{\\usebox{\\widetab}}"
               "\\end{tabular}" + tex[j:])
        tex = tex[:start] + "\\sbox{\\widetab}{" + tab + "}%\n" + tex[start:]
    return tex


def section(src: str, start: str, end: str) -> str:
    i, j = src.index(start), src.index(end)
    return src[i + len(start):j].strip()


def main() -> None:
    src = SRC.read_text()
    abstract = section(src, r"\begin{abstract}", r"\end{abstract}")
    body = src[src.index(r"\section{Introduction}"):src.index(r"\section*{Data availability}")]
    data = section(src, r"\section*{Data availability}", r"\section*{Code availability}")
    code = section(src, r"\section*{Code availability}", r"\section*{Disclosure statement}")
    appendix = src[src.index(r"\appendix") + len(r"\appendix"):src.index(r"\end{document}")]
    # one-line reference to the repository README instead of the closing
    # sentence of the Discussion, which the Declarations now cover
    body = body.replace("Code, results and figures are in the repository \\texttt{evalues4generative};\nall runs are seeded.\n", "")
    # drop the draft's adjustbox wrappers, which clash with sn-jnl's tables
    body = body.replace("\\begin{adjustbox}{max width=\\textwidth}\n", "").replace("\n\\end{adjustbox}", "")
    appendix = appendix.replace("\\begin{adjustbox}{max width=\\textwidth}\n", "").replace("\n\\end{adjustbox}", "")
    # the Springer text block is narrower: scale down the tables that overflow it
    body, appendix = shrink_wide_tables(body), shrink_wide_tables(appendix)
    out = (PREAMBLE.replace("%ABSTRACT%", abstract) + body
           + BACKMATTER.replace("%DATA%", data).replace("%CODE%", code)
           + "\\begin{appendices}\n" + appendix.strip() + "\n\\end{appendices}\n\n"
           + "\\bibliography{references}\n\n\\end{document}\n")
    (HERE / "manuscript.tex").write_text(out)
    shutil.copy(HERE.parent / "references.bib", HERE / "references.bib")
    for name in sorted(set(re.findall(r"\\includegraphics(?:\[[^]]*\])?\{([^}]*)\}", out))):
        shutil.copy(FIGS / name, HERE / name)
    print("wrote", HERE / "manuscript.tex")


if __name__ == "__main__":
    main()
