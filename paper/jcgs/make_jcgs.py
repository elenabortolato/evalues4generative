"""Build the Journal of Computational and Graphical Statistics submission from ../main.tex.

The body, appendices and bibliography are taken unchanged from the working
draft, as for the Statistics and Computing version (../stco), so the versions
cannot drift apart. Only the front and back matter are rewritten, following
the ASA LaTeX template used by JCGS and JASA: 12pt article, 1-inch margins,
line spacing 1.45 from the Introduction on, a blind switch, keywords after the
abstract, a SUPPLEMENTARY MATERIAL section and Chicago author-year references.

Set \\blind to 1 in manuscript.tex for an anonymised version: the author, the
acknowledgements and the link to the repository are then hidden.

Run from this folder:

    python make_jcgs.py
    pdflatex manuscript && bibtex manuscript && pdflatex manuscript && pdflatex manuscript
"""

from __future__ import annotations

import re
import shutil
from pathlib import Path

HERE = Path(__file__).resolve().parent
SRC = HERE.parent / "main.tex"
FIGS = HERE.parents[1] / "figures"
REPO = r"\url{https://github.com/elenabortolato/evalues4generative}"

PREAMBLE = r"""%% JCGS submission, generated by make_jcgs.py from ../main.tex.
\documentclass[12pt]{article}

\usepackage[margin=1in]{geometry}
\usepackage{amsmath,amssymb,amsthm}
\usepackage{graphicx}
\usepackage{booktabs}
\usepackage{array,longtable}
\usepackage{adjustbox}
\usepackage{enumerate}
\usepackage[round,authoryear]{natbib}
\usepackage{xurl}
\usepackage[hidelinks]{hyperref}

% 12pt leaves less room for inline formulas: allow looser lines, not overfull ones
\setlength{\emergencystretch}{3em}

\newcommand{\E}{\mathbb{E}}
\newcommand{\KL}{\mathrm{KL}}
\newcommand{\F}{\mathcal{F}}
\newcommand{\G}{\mathcal{G}}

\newtheorem{theorem}{Theorem}
\newtheorem{proposition}{Proposition}
\newtheorem{corollary}{Corollary}
\theoremstyle{remark}
\newtheorem{remark}{Remark}

% 0: version with the author; 1: anonymised version for blind review.
\newcommand{\blind}{0}

\def\spacingset#1{\renewcommand{\baselinestretch}%
{#1}\small\normalsize} \spacingset{1}

\begin{document}

\if0\blind
{
  \title{\bf Betting against the simulator:\\
  Monte Carlo e-processes under adaptive actions}
  \author{Elena Bortolato\thanks{%ACK%}\hspace{.2cm}\\
    CUNEF Universidad, Madrid, Spain}
  \date{}
  \maketitle
} \fi

\if1\blind
{
  \bigskip
  \bigskip
  \bigskip
  \begin{center}
    {\LARGE\bf Betting against the simulator:\\[4pt]
    Monte Carlo e-processes under adaptive actions}
  \end{center}
  \medskip
} \fi

\bigskip
\begin{abstract}
%ABSTRACT%
\end{abstract}

\noindent%
{\it Keywords:} e-values; anytime-valid inference; simulation-based inference;
digital twins; adaptive designs; prequential inference
\vfill

\newpage
\spacingset{1.45}
"""

BACKMATTER = r"""
\bigskip
\begin{center}
{\large\bf SUPPLEMENTARY MATERIAL}
\end{center}

\begin{description}
\item[Supplement:] three further analyses (a single patient under closed-loop
control, a single-stage response-adaptive trial, and a comparison with the
Besag--Clifford e-process) and additional results for Sections~\ref{sec:experiments}
and~\ref{sec:trial} (PDF).
\item[Code and data:] Python code for all methods, experiments, tables and
figures, with the replies of the language models of
Section~\ref{sec:exp-llm}%REPO%. The file \texttt{REPRODUCIBILITY.md} lists,
for every table and figure, the script and command that produce it, the
output file and an indication of the running time. Every replication is
seeded, so the reported numbers are reproduced exactly with the stated library
versions, up to the rounding differences across processors documented there.
\end{description}

\section*{Disclosure statement}
The author reports there are no competing interests to declare.

\section*{Data availability statement}
No external data are used. The replies of the language models in
Section~\ref{sec:exp-llm} were generated from the publicly released Qwen2.5
models and are distributed with the code; all other data are simulated by the
code.

"""

ACK = r"""The author gratefully acknowledges [funding and acknowledgements to be completed]."""


def section(src: str, start: str, end: str) -> str:
    i, j = src.index(start), src.index(end)
    return src[i + len(start):j].strip()


def main() -> None:
    src = SRC.read_text()
    abstract = section(src, r"\begin{abstract}", r"\end{abstract}")
    body = src[src.index(r"\section{Introduction}"):src.index(r"\section*{Data availability}")]
    appendix = src[src.index(r"\appendix"):src.index(r"\end{document}")]
    # the Supplementary material section points to the repository instead
    # the notation table is single-spaced, as tables are in the ASA template
    appendix = appendix.replace("{\\small\n\\setlength{\\LTpre}", "{\\spacingset{1}\\small\n\\setlength{\\LTpre}", 1)
    body = body.replace("Code, results and figures are in the repository \\texttt{evalues4generative};\nall runs are seeded.\n", "")
    repo = r"\if0\blind, at " + REPO + r"\fi\if1\blind{} (link removed for blind review)\fi"
    out = (PREAMBLE.replace("%ACK%", ACK).replace("%ABSTRACT%", abstract)
           + body.rstrip() + "\n" + BACKMATTER.replace("%REPO%", repo)
           + "\\bibliographystyle{chicago}\n\\bibliography{references}\n\n"
           + appendix.rstrip() + "\n\n\\end{document}\n")
    for name in ("sec:experiments", "sec:trial", "sec:exp-llm"):
        assert "\\label{" + name + "}" in out, name
    (HERE / "manuscript.tex").write_text(out)
    shutil.copy(HERE.parent / "references.bib", HERE / "references.bib")
    for name in sorted(set(re.findall(r"\\includegraphics(?:\[[^]]*\])?\{([^}]*)\}", out))):
        shutil.copy(FIGS / name, HERE / name)
    print("wrote", HERE / "manuscript.tex")


if __name__ == "__main__":
    main()
