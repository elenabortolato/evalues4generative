"""Experiment 8: real data. Monitoring a COVID-19 transmission twin for Italy.

Data: Italy's national daily ICU admissions (Protezione Civile) and the OxCGRT
stringency index, December 2020 to December 2022 (data/italy_covid_daily.csv).

Twin: the stochastic renewal model of e4g.epi, calibrated by maximum
likelihood on 8 weeks and then frozen. The policy effect enters with a 7-day
lag, so the stringency that drives a 7-day block is observed when the block
starts: the twin is simulated under the policy actually in force.

Part A (real data). From the end of the first calibration window, each week the
twin simulates the coming 7 days M = 16 times, and the monitor bets with the BLR
predictive score. At an alarm, the twin is recalibrated on the last 8 weeks and
a new monitor starts, which yields a timeline of dates at which the calibrated
twin stopped describing the epidemic.

Part B (validity and power on synthetic data). Series generated by the
calibrated twin itself, over the same horizon, with the policy set every week by
a data-driven tier rule (stringency 80 / 60 / 40 when last week's admissions
exceed 1000 / 400 / otherwise), mimicking Italy's colour-coded regional tiers.
  null     the data follow the twin
  variant  from week 10, transmission is multiplied by 1.4
Methods: mc_blr (the paper's monitor), plugin (BLR odds used as the bet),
nominal (twin simulated with the policy held at its calibration-window mean,
i.e. not conditioned on the action), ttest (t-test of standardised weekly
residuals, recomputed every week).

Output: results/exp8.json, figures/exp8_italy_covid.png
"""

from __future__ import annotations

import json
import sys
import time
from concurrent.futures import ProcessPoolExecutor
from functools import partial
from pathlib import Path

import numpy as np
import pandas as pd
from scipy.stats import ttest_1samp

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from e4g import BLRRatio, LambdaMixture, mc_factor, plugin_factor  # noqa: E402
from e4g import epi  # noqa: E402

M, ALPHA, BLOCK, CALIB = 16, 0.05, 7, 56
THRESH = 1 / ALPHA


def load():
    d = pd.read_csv(ROOT / "data" / "italy_covid_daily.csv", parse_dates=["date"])
    d = d[(d.date >= "2020-12-03") & (d.date <= "2022-12-31")].reset_index(drop=True)
    y = d.icu_admissions.values.astype(float)
    s = d.stringency.ffill().values.astype(float)
    wd = d.date.dt.weekday.values
    return d, y, s, wd


def rows(traces, g, s_lag):
    """Weekly summaries relative to the twin's noise-free path g (log scale)."""
    r = np.log1p(traces) - np.log1p(g)
    rbar = r.mean(1) / 0.1
    slope = (r[:, -3:].mean(1) - r[:, :3].mean(1)) / 0.1
    c = np.full(len(r), np.log1p(g.mean()) - 4.0)
    u = np.full(len(r), s_lag / 100.0 - 0.5)
    return np.column_stack([rbar, slope, c, u])


def feature_map(z):
    rbar, slope, c, u = z.T
    return np.column_stack([rbar, rbar ** 2, slope, rbar * u, rbar * c])


def new_learner(twin, y, s, wd, t0, rng):
    """Scaler from twin simulations only (no real outcomes)."""
    sims = epi.simulate_block(twin, y, s, wd, t0, BLOCK, 200, rng)
    g = epi.simulate_block(twin, y, s, wd, t0, BLOCK, 1, rng, deterministic=True)[0]
    return BLRRatio(feature_map=feature_map).fit_scaler(rows(sims, g, s[t0 - epi.LAG]))


class Monitor:
    """One monitor for one frozen twin; policy=None conditions on the actual policy."""

    def __init__(self, twin, y, s, wd, t0, rng, policy=None):
        self.twin, self.policy = twin, policy
        self.blr = new_learner(twin, y, s, wd, t0, rng)
        self.w, self.w_plug = LambdaMixture(), LambdaMixture()
        self.z = []

    def week(self, y, s, wd, t0, rng):
        """Bet on days t0..t0+6 (y must already contain them); returns the factors."""
        pol = self.policy
        sims = epi.simulate_block(self.twin, y, s, wd, t0, BLOCK, M, rng, policy=pol)
        g = epi.simulate_block(self.twin, y, s, wd, t0, BLOCK, 1, rng, deterministic=True,
                               policy=pol)[0]
        s_lag = s[t0 - epi.LAG] if pol is None else pol
        rx, ry = rows(y[None, t0:t0 + BLOCK], g, s_lag), rows(sims, g, s_lag)
        sc = self.blr.score(np.vstack([rx, ry]))
        e = mc_factor(sc[0], sc[1:])
        wv = self.w.update(e)
        wp = self.w_plug.update(plugin_factor(sc[0]))
        self.blr.update(rx, ry)
        tot = sims.sum(1)
        self.z.append((y[t0:t0 + BLOCK].sum() - tot.mean()) / (tot.std() + 1e-9))
        p = ttest_1samp(self.z, 0.0).pvalue if len(self.z) >= 3 else 1.0
        return wv, wp, p, sims


# ------------------------------------------------------------ Part A: real data

def real_data(seed=0):
    d, y, s, wd = load()
    rng = np.random.default_rng(seed)
    t_cal = epi.S
    twin = epi.fit(y, s, wd, t_cal, t_cal + CALIB, b_fixed=epi.B_POLICY)
    t0 = t_cal + CALIB
    mon = Monitor(twin, y, s, wd, t0, rng)
    log = {"date": [], "logw": [], "lo": [], "hi": [], "segment": []}
    alarms, seg, first_alarm = [], 0, None
    while t0 + BLOCK <= len(y):
        wv, _, _, sims = mon.week(y, s, wd, t0, rng)
        band = epi.simulate_block(mon.twin, y, s, wd, t0, BLOCK, 400, rng)  # display only
        for j in range(BLOCK):
            log["date"].append(str(d.date[t0 + j].date()))
            log["lo"].append(float(np.percentile(band[:, j], 5)))
            log["hi"].append(float(np.percentile(band[:, j], 95)))
            log["segment"].append(seg)
        log["logw"].append(float(np.log(wv)))
        t0 += BLOCK
        if wv >= THRESH:
            alarm_date = str(d.date[t0 - 1].date())
            alarms.append({"date": alarm_date, "weeks_monitored": len(mon.z),
                           "twin_logR": float(mon.twin.a)})
            first_alarm = first_alarm or alarm_date
            # recalibrate on the last 8 weeks and restart
            twin = epi.fit(y, s, wd, t0 - CALIB, t0, b_fixed=epi.B_POLICY)
            mon = Monitor(twin, y, s, wd, t0, rng)
            seg += 1
    return {"alarms": alarms, "first_alarm": first_alarm, "log": log,
            "calibration": [str(d.date[t_cal].date()), str(d.date[t_cal + CALIB - 1].date())],
            "twin0": {"a": float(epi.fit(y, s, wd, t_cal, t_cal + CALIB,
                                         b_fixed=epi.B_POLICY).a),
                      "b": epi.B_POLICY}}


# -------------------------------------------------------- Part B: synthetic data

def tier_policy(last_week_admissions):
    return 80.0 if last_week_admissions > 1000 else 60.0 if last_week_admissions > 400 else 40.0


def synthetic_one(seed, scenario):
    d, y_real, s_real, wd = load()
    rng = np.random.default_rng(seed)
    t_cal = epi.S
    twin = epi.fit(y_real, s_real, wd, t_cal, t_cal + CALIB, b_fixed=epi.B_POLICY)
    t_start = t_cal + CALIB
    n_weeks = (len(y_real) - t_start) // BLOCK
    y = y_real.copy()
    s = s_real.copy()
    nominal = float(s_real[t_cal - epi.LAG:t_cal + CALIB - epi.LAG].mean())
    mons = {"mc": Monitor(twin, y, s, wd, t_start, rng),
            "nominal": Monitor(twin, y, s, wd, t_start, rng, policy=nominal)}
    first = {k: None for k in ("mc_blr", "plugin", "nominal", "ttest")}
    for wk in range(n_weeks):
        t0 = t_start + wk * BLOCK
        # the policy for the coming week responds to last week's admissions
        s[t0:t0 + BLOCK] = tier_policy(y[t0 - BLOCK:t0].sum())
        mult = 1.4 if (scenario == "variant" and wk >= 10) else 1.0
        truth = epi.Twin(a=twin.a + np.log(mult), b=twin.b, k=twin.k, dow=twin.dow)
        y[t0:t0 + BLOCK] = epi.simulate_block(truth, y, s, wd, t0, BLOCK, 1, rng)[0]
        wv, wp, p, _ = mons["mc"].week(y, s, wd, t0, rng)
        wn, _, _, _ = mons["nominal"].week(y, s, wd, t0, rng)
        for k, hit in (("mc_blr", wv >= THRESH), ("plugin", wp >= THRESH),
                       ("nominal", wn >= THRESH), ("ttest", p < ALPHA)):
            if hit and first[k] is None:
                first[k] = wk + 1
    return first


def summarise(runs, scenario):
    out = {}
    for k in runs[0]:
        t = np.array([r[k] if r[k] is not None else np.inf for r in runs])
        if scenario == "null":
            out[k] = {"false_alarm": float(np.isfinite(t).mean())}
        else:
            early = t <= 10
            late = np.isfinite(t) & ~early
            out[k] = {"alarm_before_change": float(early.mean()),
                      "detected": float(late.mean()),
                      "median_delay_weeks": float(np.median(t[late] - 10)) if late.any() else None}
    return out


def main():
    t0 = time.time()
    res = {"config": dict(m=M, alpha=ALPHA, block_days=BLOCK, calib_days=CALIB,
                          b_policy=epi.B_POLICY, lag=epi.LAG)}
    res["real"] = real_data()
    print("real data: first alarm", res["real"]["first_alarm"])
    for a in res["real"]["alarms"]:
        print("   alarm", a)
    reps = {"null": 200, "variant": 100}
    res["synthetic"] = {}
    for sc, n in reps.items():
        with ProcessPoolExecutor() as ex:
            runs = list(ex.map(partial(synthetic_one, scenario=sc), range(n), chunksize=4))
        res["synthetic"][sc] = summarise(runs, sc)
        print(f"synthetic {sc}: {res['synthetic'][sc]}", flush=True)
    print(f"{time.time() - t0:.0f}s")
    (ROOT / "results" / "exp8.json").write_text(json.dumps(res, indent=1))


if __name__ == "__main__":
    main()
